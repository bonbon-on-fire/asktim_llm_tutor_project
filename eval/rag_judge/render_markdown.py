"""Render a ground-truth JSONL dataset to a human-readable Markdown companion.

The JSONL (``ground_truth/<course>.jsonl``) is the source of truth that code
reads; this writes a sibling ``<course>.md`` that's pleasant to skim and review.
Regenerate it after editing the JSONL (e.g. during the human review pass):

    python eval/rag_judge/render_markdown.py --course supply_chain_design

``generate_ground_truth.py`` also calls :func:`render` automatically, so a fresh
generation always produces the pair.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
_GT_DIR = _REPO_ROOT / "eval" / "rag_judge" / "ground_truth"


def _retrieval_line(flags: dict) -> str:
    """One-line human summary of the baseline-retrieval flags for a row."""
    if flags.get("gold_hit"):
        return f"✅ gold retrieved at rank {flags.get('gold_rank')} of {flags.get('retrieved_k')}"
    top = flags.get("top_source") or "?"
    return f"❌ gold missed (top hit: `{top}`)"


def render(rows: list[dict], course: str) -> str:
    """Return the Markdown rendering of *rows* for *course*."""
    total = len(rows)
    hits = sum(1 for r in rows if r.get("flags", {}).get("gold_hit"))
    to_review = sum(1 for r in rows if r.get("flags", {}).get("needs_review"))
    lectures = sorted({r.get("topic", "") for r in rows})

    out: list[str] = []
    out.append(f"# RAG retrieval ground truth — {course}")
    out.append("")
    out.append(
        f"> _Generated from `{course}.jsonl` — the JSONL is the source of truth. "
        f"Edit the JSONL, then re-render with `render_markdown.py`. Do not edit this file directly._"
    )
    out.append("")
    out.append(
        f"**{total}** questions · baseline retrieval found the gold in "
        f"**{hits}/{total}** · **{to_review}** awaiting review · "
        f"**{len(lectures)}** lectures covered"
    )
    out.append("")

    for row in rows:
        gold = (row.get("gold") or [{}])[0]
        flags = row.get("flags", {})
        review = " · 🔎 needs review" if flags.get("needs_review") else ""
        out.append("---")
        out.append("")
        out.append(f"### `{row.get('id')}`{review}")
        out.append("")
        out.append(f"**Q:** {row.get('question', '')}")
        out.append("")
        quote = gold.get("quote", "").replace("\n", " ").strip()
        out.append(f"> {quote}")
        out.append("")
        out.append(
            f"- **Source:** `{gold.get('source', '?')}` "
            f"(chars {gold.get('start', '?')}–{gold.get('end', '?')})"
        )
        out.append(f"- **Baseline:** {_retrieval_line(flags)}")
        out.append("")

    return "\n".join(out) + "\n"


def render_file(jsonl_path: Path, course: str) -> Path:
    """Render *jsonl_path* to a sibling ``.md`` and return the written path."""
    rows = [json.loads(line) for line in jsonl_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    md_path = jsonl_path.with_suffix(".md")
    md_path.write_text(render(rows, course), encoding="utf-8")
    return md_path


def main() -> int:
    """CLI: render ``ground_truth/<course>.jsonl`` to ``<course>.md``."""
    p = argparse.ArgumentParser(description="Render a ground-truth JSONL to a Markdown companion.")
    p.add_argument("--course", default="supply_chain_design")
    p.add_argument("--in", dest="in_path", default=None, help="JSONL path (default: ground_truth/<course>.jsonl)")
    args = p.parse_args()

    jsonl_path = Path(args.in_path) if args.in_path else _GT_DIR / f"{args.course}.jsonl"
    if not jsonl_path.exists():
        raise SystemExit(f"Dataset not found: {jsonl_path}")
    md_path = render_file(jsonl_path, args.course)
    print(f"Rendered {md_path.relative_to(_REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
